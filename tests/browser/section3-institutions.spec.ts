import { test, expect } from '@playwright/test';
import { createDemoFixture } from '../../mobile/demo-fixture';
import { DASHBOARD_STORAGE_KEY } from '../../app/data-repository';
import { APPEARANCE_KEY, THEMES } from '../../app/appearance';

test('explicit institution selection survives account/loan saves and reload without financial changes', async ({page}) => {
  const fixture=createDemoFixture();
  fixture.payload.monthlyPlan!.loanTrackers=[{id:'synthetic-loan',name:'Sample mortgage',kind:'house',originalAmount:200000,remainingAmount:180000,apr:5,escrow:100,monthlyPayment:1500,balanceKind:'principal',asOf:'2026-10-01',budgetItemId:'',budgetItemName:'',history:[{date:'2026-10-01',amount:180000,balanceKind:'principal',recordedAt:'2026-10-01T12:00:00Z'}]}];
  await page.addInitScript(({key, fixture})=>{if(!localStorage.getItem(key))localStorage.setItem(key,JSON.stringify(fixture));},{key:DASHBOARD_STORAGE_KEY,fixture});
  await page.goto('/');
  await expect(page.getByRole('heading',{name:/Welcome,/})).toBeVisible();
  await page.getByRole('button',{name:'Debt',exact:true}).click();
  await page.getByRole('button',{name:'Open Sample card',exact:true}).click();
  await page.getByRole('tab',{name:'Info',exact:true}).click();
  const picker=page.getByLabel('Institution (optional)');
  await expect(picker).toHaveValue('');
  await picker.selectOption('chase');
  await page.getByRole('button',{name:'Save',exact:true}).click();
  await expect.poll(()=>page.evaluate(key=>JSON.parse(localStorage.getItem(key)!).payload.accounts[0].institutionKey,DASHBOARD_STORAGE_KEY)).toBe('chase');
  await page.reload();
  await page.getByRole('button',{name:'Debt',exact:true}).click();
  await expect(page.getByRole('img',{name:'Chase (Credit card)',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Open Sample card',exact:true}).click();
  await page.getByRole('tab',{name:'Info',exact:true}).click();
  await expect(picker).toHaveValue('chase');
  await page.reload();
  await page.getByRole('button',{name:'Debt',exact:true}).click();
  await page.getByRole('button',{name:'Open Sample mortgage',exact:true}).click();
  await page.getByRole('tab',{name:'Info',exact:true}).click();
  await picker.selectOption('citi');
  await page.getByRole('button',{name:'Save',exact:true}).click();
  await expect.poll(()=>page.evaluate(key=>JSON.parse(localStorage.getItem(key)!).payload.monthlyPlan.loanTrackers[0].institutionKey,DASHBOARD_STORAGE_KEY)).toBe('citi');
  await page.reload();
  await page.getByRole('button',{name:'Debt',exact:true}).click();
  await expect(page.getByRole('img',{name:'Citi (Mortgage)',exact:true})).toBeVisible();
  const saved=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)!),DASHBOARD_STORAGE_KEY);
  const originalCard=fixture.payload.accounts[0];
  const savedCard=saved.payload.accounts.find((a:{id:string})=>a.id===originalCard.id);
  expect(savedCard.institutionKey).toBe('chase');
  delete savedCard.institutionKey;
  for(const key of ['id','name','balance','baselineBalance','apr','minimum'] as const) expect(savedCard[key]).toEqual(originalCard[key]);
  const savedLoan=saved.payload.monthlyPlan.loanTrackers[0];
  expect(savedLoan.institutionKey).toBe('citi');
  delete savedLoan.institutionKey;
  expect(savedLoan).toEqual(fixture.payload.monthlyPlan!.loanTrackers![0]);
  expect(saved.payload.transactions).toEqual(fixture.payload.transactions);
  expect(saved.payload.snapshots).toEqual(fixture.payload.snapshots);
  await page.screenshot({path:'outputs/section3-institutions/light.png'});
  await page.evaluate(({key,value})=>{localStorage.setItem(key,JSON.stringify(value));},{key:APPEARANCE_KEY,value:THEMES.dark});
  await page.reload();
  await page.getByRole('button',{name:'Debt',exact:true}).click();
  await expect(page.getByRole('img',{name:'Citi (Mortgage)',exact:true})).toBeVisible();
  await page.screenshot({path:'outputs/section3-institutions/dark.png'});
});
