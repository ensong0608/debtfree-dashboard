import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import AxeBuilder from '@axe-core/playwright';

test('loans persist, use Budget payments, and do not change existing debt balances', async ({ page }) => {
  const fixture = JSON.parse(readFileSync('tests/fixtures/legacy-v0.json', 'utf8'));
  const month = new Date().toLocaleDateString('en-CA', { timeZone: 'America/Los_Angeles' }).slice(0,7);
  fixture.monthlyBudgets = { [month]: [{ id:'home-bill', name:'Mortgage', kind:'expense', category:'Housing', amount:2000, paymentMethod:'debit', creditAccountId:'', createdAt:new Date().toISOString(), recurring:true }] };
  await page.goto('/');
  await page.locator('input[type="file"]').setInputFiles({ name:'loan-fixture.json', mimeType:'application/json', buffer:Buffer.from(JSON.stringify(fixture)) });
  const before = await page.locator('.simple-total>strong').innerText();
  await page.getByRole('tab',{name:'House & car',exact:true}).click();
  await expect(page.getByRole('button', { name:'+ Track loan', exact:true })).toHaveCount(0);
  await page.getByRole('button', { name:'Debt +', exact:true }).click();
  await page.getByLabel('Debt type').selectOption({label:'House loan'});
  const dialog = page.getByRole('dialog', { name:'Mortgage Details' });
  await dialog.getByLabel('Name*', { exact:true }).fill('Home');
  await dialog.getByLabel('Original balance').fill('100000');
  await dialog.getByLabel('Current balance').fill('80000');
  await dialog.getByLabel('Mortgage payment', {exact:true}).fill('2000');
  await dialog.getByLabel('APR*').fill('3.625');
  await dialog.getByLabel('Escrow amount',{exact:true}).fill('618.37');
  await dialog.getByRole('button', { name:'Save' }).click();
  const card = page.getByRole('article', { name:'Home loan progress' });
  await expect(card).toContainText('20.00% paid down');
  await expect(card).toContainText('$2,000.00');
  await expect(card).toContainText('Next payment · principal');
  await expect(page.locator('.simple-total>strong')).toHaveText('$80,000.00');
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('debtfree-dashboard-prototype-v1') ?? 'null')?.payload?.monthlyPlan?.loanTrackers?.[0]?.remainingAmount)).toBe(80000);
  await page.reload();
  await expect(page.locator('.simple-total>strong')).toHaveText(before);
  await page.getByRole('tab',{name:'House & car',exact:true}).click();
  await expect(card).toContainText('$80,000.00');
  await page.getByRole('button', {name:'Budget',exact:true}).click();
  await page.getByRole('button', {name:'Edit Mortgage',exact:true}).click();
  await page.getByRole('dialog').getByLabel(/Monthly amount/).fill('2100');
  await page.getByRole('dialog').getByRole('button',{name:/Save/}).click();
  await page.getByRole('button',{name:'Debts',exact:true}).click();
  await page.getByRole('tab',{name:'House & car',exact:true}).click();
  await expect(card).toContainText('$2,000.00');
  await page.getByRole('button',{name:'Update Home loan'}).click();
  await dialog.getByLabel('Current balance').fill('75000');
  await dialog.getByLabel('Mortgage payment', {exact:true}).fill('2100');
  await dialog.getByRole('button',{name:'Save'}).click();
  await expect(card).toContainText('25.00% paid down');

  await card.getByRole('button',{name:'Activity for Home'}).click();
  await expect(page.getByRole('dialog').locator('.debt-history')).toContainText('$80,000.00');
  await expect(page.getByRole('dialog').locator('.debt-history')).toContainText('$75,000.00');
  await page.getByRole('button',{name:'Close activity'}).click();
  await card.getByRole('button',{name:'Payment'}).click();
  const paymentDialog = page.getByRole('dialog', {name:'Record Home payment'});
  await expect(paymentDialog).toContainText('Principal deducted: $1,255.07');
  await paymentDialog.getByRole('button',{name:'Confirm payment'}).click();
  await expect(card).toContainText('$73,744.93');
  await page.reload();
  await page.getByRole('tab',{name:'House & car',exact:true}).click();
  await expect(card).toContainText('$73,744.93');
  await card.getByRole('button',{name:'Activity for Home'}).click();
  await expect(page.getByRole('dialog').locator('.debt-history')).toContainText('Payment $2,100.00');
  await page.getByRole('button',{name:'Close activity'}).click();
  const axe = await new AxeBuilder({page}).include('.loan-progress-section').withRules(['color-contrast']).analyze();
  expect(axe.violations).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
});

test('editing a legacy loan preserves its original balance, balance date, history and household snapshots', async ({ page }) => {
  const fixture=JSON.parse(readFileSync('tests/fixtures/legacy-v0.json','utf8'));
  const loan={id:'legacy-home',name:'Legacy home',kind:'house',originalAmount:100000,remainingAmount:80000,balanceKind:'payoff',asOf:'2026-10-01',budgetItemId:'legacy-bill',budgetItemName:'Legacy mortgage',apr:3.625,escrow:600,principalAndInterest:1400,history:[{date:'2026-09-01',amount:81000,balanceKind:'principal',recordedAt:'2026-09-01T12:00:00Z'}]};
  fixture.monthlyPlan={months:{},detailedSpendingTracking:false,progressStartingBalance:123456,loanTrackers:[loan]};
  await page.goto('/');
  await page.locator('input[type=file]').setInputFiles({name:'legacy-loan.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(fixture))});
  const stored=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('debtfree-dashboard-prototype-v1')!).payload);
  await expect.poll(async()=>Boolean((await stored())?.monthlyPlan?.loanTrackers?.length)).toBe(true);
  const before=await stored();
  await page.getByRole('tab',{name:'House & car',exact:true}).click();
  await page.getByRole('button',{name:'Update Legacy home loan'}).click();
  const dialog=page.getByRole('dialog',{name:'Mortgage Details',exact:true});
  await expect(dialog.getByLabel('Mortgage payment',{exact:true})).toHaveValue('2,000.00');
  await dialog.getByLabel('Name*',{exact:true}).fill('Updated legacy home');
  await dialog.getByRole('button',{name:'Save',exact:true}).click();
  await expect.poll(async()=>(await stored()).monthlyPlan.loanTrackers[0].name).toBe('Updated legacy home');
  await page.reload();
  const after=await stored();
  expect(after.monthlyPlan.loanTrackers[0]).toEqual({...loan,name:'Updated legacy home',monthlyPayment:2000});
  expect(after.monthlyPlan.progressStartingBalance).toBe(before.monthlyPlan.progressStartingBalance);
  for(const field of ['accounts','transactions','snapshots','balanceAdjustments','monthlyBudgets']) expect(after[field]).toEqual(before[field]);
});
