import { openSettings } from './navigation';
import { test, expect } from '@playwright/test';
import { readFileSync, mkdirSync } from 'node:fs';
import { parseDashboardContract } from '../../app/dashboard-data';

const fixture = () => {
  const contract = parseDashboardContract(JSON.parse(readFileSync('tests/fixtures/legacy-v0.json', 'utf8')));
  contract.payload.accounts = [{ ...contract.payload.accounts[0], id: 'category-card', name: 'Everyday card', displayGroup: 'Other', balance: 1000, baselineBalance: 1200, apr: 0, interestFee: 0 }];
  contract.payload.transactions = []; contract.payload.snapshots = []; contract.payload.balanceAdjustments = [];
  contract.payload.monthlyPlan = { months: {}, detailedSpendingTracking: false, progressStartingBalance: 1200, debtGroups: [{ id: 'Other', name: 'Shared' }] };
  return contract;
};

test('debt categories can be created in the editor, renamed in Settings and reused without changing balances or history', async ({ page }, info) => {
  await page.goto('/');
  await page.locator('input[type=file]').setInputFiles({ name: 'category-fixture.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(fixture())) });
  await page.getByRole('button', { name: 'Edit debt details for Everyday card', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByLabel('Debt category', { exact: true })).toHaveValue('Other');
  await dialog.getByLabel('Debt category', { exact: true }).selectOption('__new__');
  await expect(dialog.getByRole('button', { name: 'Save details', exact: true })).toBeDisabled();
  await dialog.getByRole('button', { name: 'Add category', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('Enter a category name');
  await dialog.getByLabel('New category name', { exact: true }).fill(' shared ');
  await dialog.getByRole('button', { name: 'Add category', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('already exists');
  await dialog.getByLabel('New category name', { exact: true }).fill('Travel');
  await dialog.getByRole('button', { name: 'Add category', exact: true }).click();
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  await openSettings(page);
  const settings = page.getByRole('region', { name: 'Debt categories', exact: true });
  await expect(settings.getByRole('button', { name: 'Edit Travel category', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Debts', exact: true }).click();
  await page.getByRole('button', { name: 'Debt +', exact: true }).click();
  await dialog.getByLabel('Account name', { exact: true }).fill('Travel card');
  await dialog.getByRole('spinbutton', {name: /^Current balance/}).fill('200');
  await dialog.getByLabel('Debt category', { exact: true }).selectOption('__new__');
  await dialog.getByLabel('New category name', { exact: true }).fill('Travel');
  mkdirSync('outputs/ui-verification/debt-categories', { recursive: true });
  await page.screenshot({ path: `outputs/ui-verification/debt-categories/${info.project.name}-add-category.png` });
  await dialog.getByRole('button', { name: 'Add category', exact: true }).click();
  await dialog.getByRole('button', { name: 'Add debt', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Travel debts', exact: true })).toContainText('Travel card');
  await openSettings(page);
  await settings.getByRole('button', { name: 'Edit Travel category', exact: true }).click();
  await settings.getByLabel('Category name', { exact: true }).fill('Shared');
  await settings.getByRole('button', { name: 'Save category', exact: true }).click();
  await expect(settings.getByRole('alert')).toContainText('already exists');
  await settings.getByLabel('Category name', { exact: true }).fill('Trips');
  await settings.getByRole('button', { name: 'Save category', exact: true }).click();
  await page.screenshot({ path: `outputs/ui-verification/debt-categories/${info.project.name}-settings.png` });
  await page.getByRole('button', { name: 'Debts', exact: true }).click();
  await page.getByRole('button', { name: 'Edit debt details for Everyday card', exact: true }).click();
  await dialog.getByLabel('Debt category', { exact: true }).selectOption({ label: 'Trips' });
  await page.screenshot({ path: `outputs/ui-verification/debt-categories/${info.project.name}-edit-debt.png` });
  await dialog.getByRole('button', { name: 'Save details', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Trips debts', exact: true }).locator('article h2')).toHaveText(['Travel card', 'Everyday card']);
  await page.reload();
  await expect(page.getByRole('region', { name: 'Trips debts', exact: true })).toContainText('Everyday card');
  const persisted = await page.evaluate(() => JSON.parse(localStorage.getItem('debtfree-dashboard-prototype-v1')!).payload);
  expect(persisted.accounts.find((a: {id:string}) => a.id === 'category-card')).toMatchObject({ balance: 1000, baselineBalance: 1200, name: 'Everyday card' });
  expect(persisted.transactions).toEqual([]);
  expect(persisted.monthlyPlan.progressStartingBalance).toBe(1200);
  expect(persisted.monthlyPlan.debtGroups).toHaveLength(2);
  expect(persisted.accounts.some((a: {newCategory?:unknown}) => a.newCategory)).toBe(false);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
});

test('Settings can add categories with unique names and new debts can choose them', async ({ page }) => {
  await page.goto('/');
  await page.locator('input[type=file]').setInputFiles({ name: 'category-fixture.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(fixture())) });
  await openSettings(page);
  const settings = page.getByRole('region', { name: 'Debt categories', exact: true });
  await settings.getByRole('button', { name: '+ Add category', exact: true }).click();
  await settings.getByLabel('New category name', { exact: true }).fill('Personal');
  await settings.getByRole('button', { name: 'Save category', exact: true }).click();
  await page.getByRole('button', { name: 'Debts', exact: true }).click();
  await page.getByRole('button', { name: 'Debt +', exact: true }).click();
  await expect(page.getByRole('dialog').getByLabel('Debt category', { exact: true }).locator('option')).toHaveText(['Shared', 'Personal', '+ Add category…']);
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click();
});
