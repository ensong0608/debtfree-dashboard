import { openMore } from './navigation';
import { test, expect } from '@playwright/test';
import { readFileSync, mkdirSync } from 'node:fs';

test('Debt + adds house and car loans directly with actionable validation and no Budget prerequisite', async ({ page }, info) => {
  if (info.project.name === 'phone') await page.setViewportSize({width:360,height:640});
  const fixture=JSON.parse(readFileSync('tests/fixtures/legacy-v0.json','utf8'));
  fixture.accounts=[{...fixture.accounts[0],id:'synthetic-card',name:'Existing synthetic card',balance:1000,baselineBalance:1200,interestFee:0,apr:0,promoEndDate:'',postPromoApr:0}];
  fixture.monthlyBudgets={}; fixture.transactions=[];fixture.snapshots=[];
  fixture.monthlyPlan={months:{},detailedSpendingTracking:false,progressStartingBalance:1200};
  await page.goto('/');
  await page.locator('input[type=file]').setInputFiles({name:'unified-synthetic.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(fixture))});
  await page.getByRole('button',{name:'Debt +',exact:true}).click();
  await page.getByLabel('Account name',{exact:true}).fill('Synthetic home');
  await page.getByRole('spinbutton', {name: /^Current balance/}).fill('80000');
  await page.getByLabel('Debt type').selectOption({label:'House loan'});
  const dialog=page.getByRole('dialog',{name:/^(Mortgage Details|Car Loan Details)$/});
  await expect(dialog.getByLabel('Name*',{exact:true})).toHaveValue('Synthetic home');
  await expect(dialog.getByLabel('Current balance',{exact:true})).toHaveValue('80,000.00');
  await expect(dialog.getByLabel('Category*')).toHaveValue('house');
  const save=dialog.getByRole('button',{name:'Save',exact:true});
  await expect(save).toBeEnabled();
  await save.click();
  await expect(dialog.getByText('Enter an original loan amount greater than $0.',{exact:true})).toBeVisible();
  await expect(dialog.getByLabel('Original balance',{exact:true})).toBeFocused();
  mkdirSync('outputs/ui-verification/unified-loans',{recursive:true});
  await page.screenshot({path:`outputs/ui-verification/unified-loans/${info.project.name}-validation.png`});
  await dialog.getByLabel('Original balance',{exact:true}).fill('100000');
  await dialog.getByLabel('APR*',{exact:true}).fill('-1');
  await save.click();
  await expect(dialog.getByText('Enter an APR from 0% to 100%.',{exact:true})).toBeVisible();
  await expect(dialog.getByLabel('APR*',{exact:true})).toBeFocused();
  await dialog.getByLabel('APR*',{exact:true}).fill('0');
  await expect(dialog.getByRole('button',{name:/Use Pennymac terms/})).toHaveCount(0);
  if(page.viewportSize()!.width<=700) {
    const box=await dialog.boundingBox(); expect(box!.x).toBe(0); expect(box!.width).toBe(page.viewportSize()!.width); expect(box!.height).toBe(page.viewportSize()!.height);
  }
  await dialog.getByLabel('Mortgage payment',{exact:true}).fill('2000.50');
  await dialog.getByLabel('Escrow amount',{exact:true}).fill('600.25');
  const now=new Date();
  await expect(dialog.locator('.loan-calendar-heading strong')).toHaveText(now.toLocaleDateString('en-US',{month:'long',year:'numeric',timeZone:'America/Los_Angeles'}));
  await dialog.getByRole('button',{name:'Next month',exact:true}).click();
  const dateButton=dialog.locator('.loan-calendar-grid button').nth(14);
  const dueDate=await dateButton.getAttribute('aria-label');
  await dateButton.click();
  await expect(dialog.getByLabel('Next payment DueDate')).toHaveValue(dueDate!);
  await save.click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('tab',{name:'House & car',exact:true})).toHaveAttribute('aria-selected','true');
  await expect(page.getByRole('article',{name:'Synthetic home loan progress',exact:true})).toContainText('House loan');
  await page.getByRole('button',{name:'Debt +',exact:true}).click();
  await page.getByLabel('Account name',{exact:true}).fill('Synthetic car');
  await page.getByLabel('Debt type').selectOption({label:'Car loan'});
  await expect(dialog.getByLabel('Category*')).toHaveValue('car');
  await save.click();
  await expect(dialog.getByText('Enter a remaining amount of $0 or more.',{exact:true})).toBeVisible();
  await dialog.getByLabel('Original balance',{exact:true}).fill('25000');
  await dialog.getByLabel('Current balance',{exact:true}).fill('20000');
  await expect(dialog.getByLabel('Escrow amount',{exact:true})).toHaveCount(0);
  await dialog.getByLabel('Minimum payment',{exact:true}).fill('450.75');
  await save.click();
  await expect(page.getByRole('article',{name:'Synthetic car loan progress',exact:true})).toContainText('Car loan');
  await page.reload();
  await expect(page.locator('.simple-total>strong')).toHaveText('$1,000.00');
  await page.getByRole('tab',{name:'House & car',exact:true}).click();
  await expect(page.locator('.loan-progress-card')).toHaveCount(2);
  await page.getByRole('button',{name:'Update Synthetic home loan',exact:true}).click();
  await expect(dialog.getByLabel('Mortgage payment',{exact:true})).toHaveValue('2,000.50');
  await expect(dialog.getByLabel('Original balance',{exact:true})).toHaveValue('100,000.00');
  await expect(dialog.getByLabel('Next payment DueDate')).toHaveValue(dueDate!);
  await expect(dialog.getByLabel('Balance type')).toHaveCount(0);
  await expect(dialog.getByLabel('Balance date')).toHaveCount(0);
  await dialog.getByLabel('Name*',{exact:true}).fill('Renamed home');
  await save.click();
  await page.getByRole('button',{name:'Update Synthetic car loan',exact:true}).click();
  await expect(dialog.getByLabel('Minimum payment',{exact:true})).toHaveValue('450.75');
  await dialog.getByLabel('Minimum payment',{exact:true}).fill('500.25');
  await save.click();
  await page.reload();
  await page.getByRole('tab',{name:'House & car',exact:true}).click();
  await page.getByRole('button',{name:'Update Synthetic car loan',exact:true}).click();
  await expect(dialog.getByLabel('Minimum payment',{exact:true})).toHaveValue('500.25');
  await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
  await openMore(page);
  await page.getByRole('button',{name:'Progress',exact:true}).filter({visible:true}).click();
  await expect(page.locator('.actual-progress-summary')).toContainText('$1,200.00');
  await expect(page.locator('.actual-progress-summary')).toContainText('$1,000.00');
});
